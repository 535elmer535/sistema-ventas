
BEGIN;

CREATE TABLE IF NOT EXISTS public.movimientos_stock (
  id_movimiento bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_producto bigint NOT NULL
    REFERENCES public.productos(id_producto),
  id_usuario bigint NOT NULL
    REFERENCES public.usuarios(id_usuario),
  solicitud_id uuid NOT NULL UNIQUE,
  tipo text NOT NULL CHECK (tipo = 'reposicion'),
  cantidad integer NOT NULL CHECK (cantidad > 0),
  existencia_anterior integer NOT NULL CHECK (existencia_anterior >= 0),
  existencia_nueva integer NOT NULL CHECK (existencia_nueva >= 0),
  motivo text NOT NULL,
  fecha_movimiento timestamptz NOT NULL DEFAULT now(),
  CHECK (
    existencia_nueva::bigint =
    existencia_anterior::bigint + cantidad::bigint
  )
);

ALTER TABLE public.movimientos_stock ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS movimientos_stock_lectura
ON public.movimientos_stock;

CREATE POLICY movimientos_stock_lectura
ON public.movimientos_stock
FOR SELECT
TO authenticated
USING (
  EXISTS (
    SELECT 1
    FROM public.usuarios AS u
    WHERE u.id_auth = auth.uid()
      AND u.rol IN ('administrador', 'vendedor')
  )
);

REVOKE ALL ON TABLE public.movimientos_stock
FROM PUBLIC, anon, authenticated;

GRANT SELECT ON TABLE public.movimientos_stock
TO authenticated;

CREATE OR REPLACE FUNCTION public.reponer_stock_seguro(
  p_solicitud_id uuid,
  p_id_producto bigint,
  p_cantidad integer,
  p_motivo text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario bigint;
  v_rol text;
  v_anterior integer;
  v_nueva bigint;
  v_id_movimiento bigint;
  v_motivo text := nullif(btrim(p_motivo), '');
  v_existente public.movimientos_stock%ROWTYPE;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Debes iniciar sesión.';
  END IF;

  BEGIN
    SELECT u.id_usuario, u.rol
    INTO STRICT v_usuario, v_rol
    FROM public.usuarios AS u
    WHERE u.id_auth = auth.uid()
    FOR SHARE;
  EXCEPTION
    WHEN no_data_found OR too_many_rows THEN
      RAISE EXCEPTION 'Tu cuenta necesita revisión en usuarios.';
  END;

  IF v_rol IS DISTINCT FROM 'administrador' THEN
    RAISE EXCEPTION
      'Solo el administrador puede registrar reposiciones.';
  END IF;

  IF p_solicitud_id IS NULL
     OR p_id_producto IS NULL
     OR p_id_producto <= 0
     OR p_cantidad IS NULL
     OR p_cantidad <= 0 THEN
    RAISE EXCEPTION
      'Selecciona un mueble y una cantidad entera mayor que cero.';
  END IF;

  IF v_motivo IS NULL OR char_length(v_motivo) > 500 THEN
    RAISE EXCEPTION 'Escribe un motivo de hasta 500 caracteres.';
  END IF;

  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(p_solicitud_id::text, 4)
  );

  SELECT *
  INTO v_existente
  FROM public.movimientos_stock
  WHERE solicitud_id = p_solicitud_id;

  IF FOUND THEN
    IF v_existente.id_usuario IS DISTINCT FROM v_usuario
       OR v_existente.id_producto IS DISTINCT FROM p_id_producto
       OR v_existente.cantidad IS DISTINCT FROM p_cantidad
       OR v_existente.motivo IS DISTINCT FROM v_motivo THEN
      RAISE EXCEPTION
        'La solicitud ya corresponde a otro movimiento.';
    END IF;

    RETURN jsonb_build_object(
      'id_movimiento', v_existente.id_movimiento,
      'id_producto', v_existente.id_producto,
      'existencia_anterior', v_existente.existencia_anterior,
      'existencia_nueva', v_existente.existencia_nueva,
      'ya_registrado', true
    );
  END IF;

  SELECT p.existencia
  INTO v_anterior
  FROM public.productos AS p
  WHERE p.id_producto = p_id_producto
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'El mueble seleccionado ya no existe.';
  END IF;

  IF v_anterior IS NULL OR v_anterior < 0 THEN
    RAISE EXCEPTION 'La existencia actual necesita revisión.';
  END IF;

  v_nueva := v_anterior::bigint + p_cantidad::bigint;

  IF v_nueva > 2147483647 THEN
    RAISE EXCEPTION 'La existencia supera el máximo permitido.';
  END IF;

  UPDATE public.productos
  SET existencia = v_nueva::integer
  WHERE id_producto = p_id_producto;

  INSERT INTO public.movimientos_stock (
    id_producto,
    id_usuario,
    solicitud_id,
    tipo,
    cantidad,
    existencia_anterior,
    existencia_nueva,
    motivo
  )
  VALUES (
    p_id_producto,
    v_usuario,
    p_solicitud_id,
    'reposicion',
    p_cantidad,
    v_anterior,
    v_nueva::integer,
    v_motivo
  )
  RETURNING id_movimiento INTO v_id_movimiento;

  RETURN jsonb_build_object(
    'id_movimiento', v_id_movimiento,
    'id_producto', p_id_producto,
    'existencia_anterior', v_anterior,
    'existencia_nueva', v_nueva,
    'ya_registrado', false
  );
END;
$$;

REVOKE ALL ON FUNCTION public.reponer_stock_seguro(
  uuid, bigint, integer, text
) FROM PUBLIC, anon;

GRANT EXECUTE ON FUNCTION public.reponer_stock_seguro(
  uuid, bigint, integer, text
) TO authenticated;

COMMIT;




SELECT
  m.id_movimiento,
  p.nombre AS mueble,
  m.cantidad AS unidades_ingresadas,
  m.existencia_anterior,
  m.existencia_nueva,
  m.motivo,
  u.nombre AS registrado_por,
  m.fecha_movimiento AT TIME ZONE 'America/La_Paz'
    AS fecha_bolivia
FROM public.movimientos_stock AS m
JOIN public.productos AS p
  ON p.id_producto = m.id_producto
JOIN public.usuarios AS u
  ON u.id_usuario = m.id_usuario
ORDER BY m.id_movimiento DESC
LIMIT 20;