
BEGIN;

CREATE TABLE IF NOT EXISTS public.historial_estados_pedidos (
  id_historial bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pedido bigint NOT NULL
    REFERENCES public.pedidos_personalizados(id_pedido),
  id_usuario bigint NOT NULL
    REFERENCES public.usuarios(id_usuario),
  estado_anterior text NOT NULL,
  estado_nuevo text NOT NULL,
  fecha_cambio timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.historial_estados_pedidos
  ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS historial_estados_lectura
ON public.historial_estados_pedidos;

CREATE POLICY historial_estados_lectura
ON public.historial_estados_pedidos
FOR SELECT
TO authenticated
USING (
  EXISTS (
    SELECT 1
    FROM public.usuarios u
    WHERE u.id_auth = auth.uid()
      AND u.rol IN ('administrador', 'vendedor')
  )
);

REVOKE ALL ON TABLE public.historial_estados_pedidos
FROM PUBLIC, anon, authenticated;

GRANT SELECT ON TABLE public.historial_estados_pedidos
TO authenticated;

CREATE OR REPLACE FUNCTION public.avanzar_estado_pedido(
  p_id_pedido bigint,
  p_estado_actual text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario bigint;
  v_rol text;
  v_id_venta bigint;
  v_estado_pago text;
  v_estado text;
  v_siguiente text;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Debes iniciar sesión.';
  END IF;

  BEGIN
    SELECT u.id_usuario, u.rol
    INTO STRICT v_usuario, v_rol
    FROM public.usuarios u
    WHERE u.id_auth = auth.uid()
    FOR SHARE;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RAISE EXCEPTION 'Tu cuenta no tiene un perfil asociado.';
    WHEN TOO_MANY_ROWS THEN
      RAISE EXCEPTION 'Tu cuenta tiene perfiles duplicados.';
  END;

  IF v_rol IS NULL
     OR v_rol NOT IN ('administrador', 'vendedor') THEN
    RAISE EXCEPTION 'Tu cuenta no puede actualizar el estado del taller.';
  END IF;

  IF p_id_pedido IS NULL OR p_id_pedido <= 0 THEN
    RAISE EXCEPTION 'Selecciona un mueble del pedido.';
  END IF;

  SELECT pp.id_venta
  INTO v_id_venta
  FROM public.pedidos_personalizados pp
  WHERE pp.id_pedido = p_id_pedido;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'El mueble del pedido ya no existe.';
  END IF;

  -- Bloquear primero la venta y después el mueble del pedido.
  SELECT v.estado_pago
  INTO v_estado_pago
  FROM public.ventas v
  WHERE v.id_venta = v_id_venta
    AND v.tipo_venta = 'pedido_medida'
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'No se encontró la venta asociada al pedido.';
  END IF;

  IF v_estado_pago IS NULL
     OR v_estado_pago NOT IN (
       'pendiente', 'anticipo_cobrado', 'pagado'
     ) THEN
    RAISE EXCEPTION 'El estado de esta operación no permite avanzar la fabricación.';
  END IF;

  SELECT pp.estado_taller
  INTO v_estado
  FROM public.pedidos_personalizados pp
  WHERE pp.id_pedido = p_id_pedido
    AND pp.id_venta = v_id_venta
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'El mueble del pedido ya no está disponible.';
  END IF;

  IF v_estado IS DISTINCT FROM p_estado_actual THEN
    RAISE EXCEPTION 'El estado cambió. Abre nuevamente el detalle antes de continuar.';
  END IF;

  v_siguiente := CASE v_estado
    WHEN 'pendiente' THEN 'en_fabricacion'
    WHEN 'en_fabricacion' THEN 'listo'
    WHEN 'listo' THEN 'entregado'
    ELSE NULL
  END;

  IF v_siguiente IS NULL THEN
    RAISE EXCEPTION 'Este mueble ya fue entregado o tiene un estado que requiere revisión.';
  END IF;

  UPDATE public.pedidos_personalizados
  SET estado_taller = v_siguiente
  WHERE id_pedido = p_id_pedido;

  INSERT INTO public.historial_estados_pedidos (
    id_pedido,
    id_usuario,
    estado_anterior,
    estado_nuevo
  )
  VALUES (
    p_id_pedido,
    v_usuario,
    v_estado,
    v_siguiente
  );

  RETURN jsonb_build_object(
    'id_pedido', p_id_pedido,
    'id_venta', v_id_venta,
    'estado_anterior', v_estado,
    'estado_nuevo', v_siguiente
  );
END;
$$;

REVOKE ALL ON FUNCTION public.avanzar_estado_pedido(bigint, text)
FROM PUBLIC, anon;

GRANT EXECUTE ON FUNCTION public.avanzar_estado_pedido(bigint, text)
TO authenticated;

COMMIT;