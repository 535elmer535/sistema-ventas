-- MUEBLEX: mejora 10 - anulación con devolución completa.
-- Requiere las mejoras 01 a 09 ya aplicadas.
-- Conserva los cobros originales y registra por separado el dinero devuelto.
-- No realiza transferencias bancarias ni entrega efectivo.
-- Solo permite anular pedidos a medida que todavía no estén entregados.
-- Crear esta estructura NO anula operaciones ni registra devoluciones.

BEGIN;

CREATE TABLE IF NOT EXISTS public.devoluciones (
  id_devolucion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_venta bigint NOT NULL UNIQUE REFERENCES public.ventas(id_venta),
  id_usuario bigint NOT NULL REFERENCES public.usuarios(id_usuario),
  solicitud_id uuid NOT NULL UNIQUE,
  monto numeric NOT NULL CHECK (
    monto > 0 AND monto <= 90071992547409.91
    AND monto = round(monto, 2)
  ),
  metodo_devolucion text NOT NULL CHECK (
    metodo_devolucion IN ('efectivo', 'QR', 'transferencia')
  ),
  motivo text NOT NULL CHECK (
    char_length(btrim(motivo)) BETWEEN 1 AND 500
  ),
  fecha_devolucion timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.devoluciones ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS devoluciones_lectura ON public.devoluciones;
CREATE POLICY devoluciones_lectura ON public.devoluciones
FOR SELECT TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM public.usuarios AS u
    WHERE u.id_auth = auth.uid()
      AND u.rol IN ('administrador', 'vendedor')
  )
);
REVOKE ALL ON TABLE public.devoluciones FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.devoluciones TO authenticated;

CREATE OR REPLACE FUNCTION public.anular_operacion_con_devolucion(
  p_solicitud_id uuid,
  p_id_venta bigint,
  p_monto_centavos bigint,
  p_metodo text,
  p_motivo text,
  p_stock_recibido boolean
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_usuario bigint;
  v_rol text;
  v_venta public.ventas%ROWTYPE;
  v_devolucion public.devoluciones%ROWTYPE;
  v_motivo text := nullif(btrim(p_motivo), '');
  v_producto record;
  v_reintegros jsonb := '[]'::jsonb;
  v_cobrado numeric;
  v_id_devolucion bigint;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Debes iniciar sesión.';
  END IF;

  BEGIN
    SELECT u.id_usuario, u.rol INTO STRICT v_usuario, v_rol
    FROM public.usuarios AS u
    WHERE u.id_auth = auth.uid()
    FOR SHARE;
  EXCEPTION
    WHEN no_data_found OR too_many_rows THEN
      RAISE EXCEPTION 'Tu cuenta necesita revisión en usuarios.';
  END;

  IF v_rol IS DISTINCT FROM 'administrador' THEN
    RAISE EXCEPTION 'Solo el administrador puede anular y registrar devoluciones.';
  END IF;

  IF p_solicitud_id IS NULL OR p_id_venta IS NULL OR p_id_venta <= 0 THEN
    RAISE EXCEPTION 'La solicitud y la operación deben ser válidas.';
  END IF;

  IF p_monto_centavos IS NULL OR p_monto_centavos <= 0
     OR p_monto_centavos > 9007199254740991 THEN
    RAISE EXCEPTION 'El importe a devolver no es válido.';
  END IF;

  IF p_metodo IS NULL OR p_metodo NOT IN ('efectivo', 'QR', 'transferencia') THEN
    RAISE EXCEPTION 'Selecciona un método de devolución válido.';
  END IF;

  IF v_motivo IS NULL OR char_length(v_motivo) > 500 THEN
    RAISE EXCEPTION 'Escribe un motivo de hasta 500 caracteres.';
  END IF;

  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(p_solicitud_id::text, 10)
  );

  -- El mismo bloqueo se utiliza al registrar cobros y anulaciones sin cobros.
  SELECT * INTO v_venta FROM public.ventas
  WHERE id_venta = p_id_venta FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'No se encontró la operación.';
  END IF;

  SELECT * INTO v_devolucion FROM public.devoluciones
  WHERE solicitud_id = p_solicitud_id;
  IF FOUND THEN
    IF v_devolucion.id_venta IS DISTINCT FROM p_id_venta
       OR v_devolucion.id_usuario IS DISTINCT FROM v_usuario
       OR v_devolucion.monto IS DISTINCT FROM p_monto_centavos::numeric / 100
       OR v_devolucion.metodo_devolucion IS DISTINCT FROM p_metodo
       OR v_devolucion.motivo IS DISTINCT FROM v_motivo THEN
      RAISE EXCEPTION 'La solicitud corresponde a otra devolución.';
    END IF;
    RETURN jsonb_build_object(
      'id_venta', p_id_venta,
      'id_devolucion', v_devolucion.id_devolucion,
      'monto', v_devolucion.monto,
      'ya_registrada', true,
      'stock_reintegrado', v_venta.stock_reintegrado
    );
  END IF;

  IF v_venta.estado_operacion IS DISTINCT FROM 'activa' THEN
    RAISE EXCEPTION 'La operación ya está anulada. Consulta su detalle.';
  END IF;

  IF v_venta.tipo_venta IS NULL OR v_venta.tipo_venta NOT IN ('directa_stock', 'pedido_medida')
     OR v_venta.stock_reintegrado THEN
    RAISE EXCEPTION 'Esta operación necesita revisión.';
  END IF;

  IF EXISTS (SELECT 1 FROM public.devoluciones WHERE id_venta = p_id_venta) THEN
    RAISE EXCEPTION 'La operación ya tiene una devolución registrada.';
  END IF;

  IF v_venta.total IS NULL OR v_venta.total <= 0
     OR v_venta.total > 90071992547409.91
     OR v_venta.total <> round(v_venta.total, 2) THEN
    RAISE EXCEPTION 'El total de la operación necesita revisión.';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.pagos WHERE id_venta = p_id_venta
      AND (monto IS NULL OR monto <= 0 OR monto > 90071992547409.91
           OR monto <> round(monto, 2))
  ) THEN
    RAISE EXCEPTION 'Los cobros de la operación necesitan revisión.';
  END IF;

  SELECT coalesce(sum(monto), 0) INTO v_cobrado
  FROM public.pagos WHERE id_venta = p_id_venta;

  IF v_cobrado <= 0 THEN
    RAISE EXCEPTION 'La operación no tiene cobros. Utiliza la anulación sin cobros.';
  END IF;
  IF v_cobrado > v_venta.total THEN
    RAISE EXCEPTION 'Lo cobrado supera el total y necesita revisión.';
  END IF;
  IF v_cobrado * 100 <> p_monto_centavos::numeric THEN
    RAISE EXCEPTION 'Los cobros cambiaron. Abre nuevamente el detalle para confirmar el importe completo.';
  END IF;

  IF v_venta.estado_pago IS DISTINCT FROM
     (CASE WHEN v_cobrado = v_venta.total THEN 'pagado' ELSE 'anticipo_cobrado' END) THEN
    RAISE EXCEPTION 'El estado de los pagos necesita revisión.';
  END IF;

  IF v_venta.tipo_venta = 'pedido_medida' THEN
    IF NOT EXISTS (
      SELECT 1
      FROM public.pedidos_personalizados
      WHERE id_venta = p_id_venta
    ) THEN
      RAISE EXCEPTION 'El pedido no tiene muebles registrados.';
    END IF;

    IF EXISTS (
      SELECT 1
      FROM public.pedidos_personalizados
      WHERE id_venta = p_id_venta
        AND (
          estado_taller IS NULL
          OR estado_taller NOT IN (
            'pendiente', 'en_fabricacion', 'listo'
          )
        )
    ) THEN
      RAISE EXCEPTION
        'El pedido está entregado o su estado necesita revisión.';
    END IF;
  ELSE
    IF p_stock_recibido IS DISTINCT FROM true THEN
      RAISE EXCEPTION 'Confirma la recuperación del mueble antes de reintegrar stock.';
    END IF;

    IF NOT v_venta.stock_descontado THEN
      RAISE EXCEPTION
        'Esta venta antigua no tiene descuento de stock confirmado. Requiere revisión.';
    END IF;

    IF NOT EXISTS (
      SELECT 1
      FROM public.detalle_ventas
      WHERE id_venta = p_id_venta
    ) OR EXISTS (
      SELECT 1
      FROM public.detalle_ventas
      WHERE id_venta = p_id_venta
        AND (cantidad IS NULL OR cantidad <= 0)
    ) THEN
      RAISE EXCEPTION 'Las cantidades de la venta necesitan revisión.';
    END IF;

    -- Bloquear los muebles en un orden fijo.
    PERFORM p.id_producto
    FROM public.productos AS p
    WHERE p.id_producto IN (
      SELECT d.id_producto
      FROM public.detalle_ventas AS d
      WHERE d.id_venta = p_id_venta
    )
    ORDER BY p.id_producto
    FOR UPDATE;

    FOR v_producto IN
      SELECT
        p.id_producto,
        p.existencia,
        sum(d.cantidad::bigint) AS cantidad
      FROM public.detalle_ventas AS d
      JOIN public.productos AS p
        ON p.id_producto = d.id_producto
      WHERE d.id_venta = p_id_venta
      GROUP BY p.id_producto, p.existencia
      ORDER BY p.id_producto
    LOOP
      IF v_producto.existencia IS NULL
         OR v_producto.existencia < 0
         OR v_producto.existencia::numeric
            + v_producto.cantidad > 2147483647 THEN
        RAISE EXCEPTION
          'La existencia no permite completar el reintegro.';
      END IF;

      UPDATE public.productos
      SET existencia = (
        v_producto.existencia + v_producto.cantidad
      )::integer
      WHERE id_producto = v_producto.id_producto;

      v_reintegros := v_reintegros || jsonb_build_array(
        jsonb_build_object(
          'id_producto', v_producto.id_producto,
          'cantidad', v_producto.cantidad,
          'existencia_anterior', v_producto.existencia,
          'existencia_nueva',
            v_producto.existencia + v_producto.cantidad
        )
      );
    END LOOP;
  END IF;


  INSERT INTO public.devoluciones (
    id_venta, id_usuario, solicitud_id, monto, metodo_devolucion, motivo
  ) VALUES (
    p_id_venta, v_usuario, p_solicitud_id, v_cobrado, p_metodo, v_motivo
  ) RETURNING id_devolucion INTO v_id_devolucion;

  UPDATE public.ventas SET
    estado_operacion = 'anulada',
    motivo_anulacion = v_motivo,
    fecha_anulacion = now(),
    id_usuario_anulacion = v_usuario,
    stock_reintegrado = (tipo_venta = 'directa_stock'),
    detalle_reintegro_stock = v_reintegros
  WHERE id_venta = p_id_venta;

  RETURN jsonb_build_object(
    'id_venta', p_id_venta,
    'id_devolucion', v_id_devolucion,
    'monto', v_cobrado,
    'ya_registrada', false,
    'stock_reintegrado', v_venta.tipo_venta = 'directa_stock',
    'reintegros', v_reintegros
  );
END;
$function$;

REVOKE ALL ON FUNCTION public.anular_operacion_con_devolucion(
  uuid, bigint, bigint, text, text, boolean
) FROM PUBLIC, anon;

GRANT EXECUTE ON FUNCTION public.anular_operacion_con_devolucion(
  uuid, bigint, bigint, text, text, boolean
) TO authenticated;

COMMIT;
